import assert from 'node:assert/strict';
import { chromium } from 'playwright-core';
import { mkdirSync, writeFileSync, cpSync, rmSync, readFileSync } from 'node:fs';
import path from 'node:path';
const baseUrl = process.env.STUDIO_URL || 'http://127.0.0.1:5194';
const root = path.resolve(import.meta.dirname, '../..');
const id = `review_check_${Date.now()}`;
const dir = path.join(root, 'projects', id);
mkdirSync(path.join(dir, 'data'), { recursive: true });
mkdirSync(path.join(dir, 'assets/audio'), { recursive: true });
mkdirSync(path.join(dir, 'scenes'), { recursive: true });
cpSync(path.join(root, 'app/src/runtime/blank.ts'), path.join(dir, 'scenes/battlemap.ts'));
writeFileSync(path.join(dir, 'project.json'), JSON.stringify({ schemaVersion: 1, id, name: 'Review verification', duration: 15, hasAudio: true, voiceFile: 'assets/audio/voice.wav' }));
writeFileSync(path.join(dir, 'timeline.json'), JSON.stringify([{ id: 'first', scene: 'battlemap', start: 0, end: 8 }, { id: 'second', scene: 'battlemap', start: 8, end: 15 }]));
writeFileSync(path.join(dir, 'data/transcript.json'), JSON.stringify({ segments: [{ start: 0, end: 7, text: 'Cảnh đầu tiên.' }, { start: 8, end: 14, text: 'Cảnh thứ hai để kiểm tra đồng bộ lời đọc.' }] }));
const rate = 8000, wav = Buffer.alloc(44 + rate * 15 * 2);
wav.write('RIFF', 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write('WAVEfmt ', 8); wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22); wav.writeUInt32LE(rate, 24); wav.writeUInt32LE(rate * 2, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34); wav.write('data', 36); wav.writeUInt32LE(wav.length - 44, 40);
for (let i = 0; i < rate * 15; i++) wav.writeInt16LE(Math.round(Math.sin(i / rate * Math.PI * 440) * 4000), 44 + i * 2);
writeFileSync(path.join(dir, 'assets/audio/voice.wav'), wav);
const browser = await chromium.launch({ channel: 'chrome', headless: true });
try {
 const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
 const errors: string[] = []; page.on('pageerror', e => errors.push(e.message));
 await page.goto(`${baseUrl}/?project=${id}`);
 await page.waitForSelector('.review-clip');
 await page.waitForFunction(() => document.querySelector('#wave-status')?.textContent === 'Voice');
 assert.equal(await page.locator('.review-clip').count(), 2);
 await page.getByRole('button', { name: 'Lời đọc', exact: true }).click();
 await page.locator('.transcript-row').nth(1).click();
 await page.waitForFunction(() => document.querySelector('#player-current')?.textContent === '0:08');
 assert.ok(await page.locator('.transcript-row').nth(1).evaluate(e => e.classList.contains('active')));
 await page.getByRole('button', { name: 'Ghi chú', exact: true }).click();
 await page.getByLabel('Nội dung ghi chú').fill('Phóng to xe tăng <script>safe</script>');
 await page.getByRole('button', { name: 'Ghi chú tại thời điểm hiện tại', exact: true }).click();
 await page.waitForFunction(() => document.querySelector('#review-notes [role=status]')?.textContent === 'Đã lưu vào project.');
 assert.equal(JSON.parse(readFileSync(path.join(dir, 'data/review-notes.json'), 'utf8'))[0].time, 8);
 await page.reload(); await page.waitForSelector('.review-clip');
 await page.getByRole('button', { name: 'Ghi chú', exact: true }).click();
 await page.getByRole('button', { name: 'Đã xử lý', exact: true }).click();
 await page.waitForSelector('.review-note.done');
 await page.getByRole('button', { name: 'Mở lại', exact: true }).click();
 await page.waitForFunction(() => !document.querySelector('.review-note.done'));
 const handle = page.locator('[data-entry="first"] .end');
 const box = (await handle.boundingBox())!;
 await page.mouse.move(box.x + box.width / 2, box.y + 10); await page.mouse.down(); await page.mouse.move(box.x - 100, box.y + 10, { steps: 8 }); await page.mouse.up();
 await page.getByRole('button', { name: 'Cảnh', exact: true }).click();
 const end = Number(await page.getByLabel('first: Kết thúc').inputValue()); assert.ok(end < 8 && end > 6);
 await page.getByRole('button', { name: 'Lời đọc', exact: true }).click();
 assert.ok(await page.locator('.transcript-row.uncovered').count() > 0);
 await page.getByRole('button', { name: 'Cảnh', exact: true }).click();
 await Promise.all([page.waitForEvent('load'), page.getByRole('button', { name: 'Lưu Timeline', exact: true }).click()]);
 await page.waitForSelector('.review-clip');
 assert.equal(JSON.parse(readFileSync(path.join(dir, 'timeline.json'), 'utf8'))[0].end, end);
 await page.locator('#review-zoom').fill('3'); await page.locator('#review-zoom').dispatchEvent('input');
 assert.ok(await page.locator('#review-scroll').evaluate(e => e.scrollWidth > e.clientWidth * 2));
 const invalid = await page.request.post(`${baseUrl}/api/review-notes`, { data: { projectId: id, notes: [{ id: 'bad', time: -1, text: 'bad', done: false }] } }); assert.equal(invalid.status(), 400);
 await page.getByRole('button', { name: 'Ghi chú', exact: true }).click();
 await page.screenshot({ path: '/tmp/pdoom-review.png' });
 assert.deepEqual(errors, []);
 console.log('PASS: waveform, transcript seek/highlight, notes persistence and completion, timeline drag/save, uncovered speech, zoom, API validation, no browser errors');
} finally { await browser.close(); rmSync(dir, { recursive: true, force: true }); }
